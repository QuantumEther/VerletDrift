// Run: node scripts/compare-suspension.mjs. Uses real physics without rendering.
import { pathToFileURL } from 'node:url';
globalThis.localStorage ??= { getItem: () => null, setItem: () => {} };
const { default: state } = await import('../js/state.js');
const { initializeCarBody, computeBodyDerivedState } = await import('../js/physics/kinematics.js');
const { updateSuspension } = await import('../js/physics/suspension.js');
const { computeTireForces, computeDragForces } = await import('../js/physics/tires.js');
const { verletIntegrateAllPoints } = await import('../js/physics/integrator.js');
const { solveRigidBodyConstraints } = await import('../js/physics/constraints.js');
const { CAR_HALF_LENGTH: L, CAR_HALF_WIDTH: W } = await import('../js/constants.js');
const initial = structuredClone(state);

export function compareRun({ enabled = true, sensitivity = 0.12, frontBar = 12000,
  rearBar = 8000, dt = 0.01, maneuver = 'transition' } = {}) {
  Object.assign(state, structuredClone(initial));
  Object.assign(state.params, { suspensionEnabled: enabled, tireLoadSensitivity: sensitivity,
    antiRollStiffnessFront: frontBar, antiRollStiffnessRear: rearBar });
  initializeCarBody(100, 100);
  state.engine.currentGear = maneuver === 'acceleration' ? '1' : 'N';
  state.engine.clutchEngagement = 1;
  state.engine.transmittedTorqueNm = maneuver === 'acceleration' ? 100 : 0;
  state.input.throttleKeyHeld = maneuver === 'acceleration';
  const speed = maneuver === 'acceleration' ? 5 : 20;
  for (const [name, wheel] of Object.entries(state.wheels)) {
    wheel.prevY = wheel.y + speed * dt;
    state.wheelOmega[name] = speed / state.params.wheelRadius;
  }
  computeBodyDerivedState(dt);
  // Starting speed was imposed, not generated by a one-tick impulse.
  state.body.longitudinalAccel = state.body.lateralAccel = 0;
  let maxRoll = 0, maxSlip = 0, maxYaw = 0, minLoad = Infinity;
  const samples = [];
  for (let i = 0; i < Math.round(3 / dt); i++) {
    const t = i * dt;
    state.input.brakeKeyHeld = maneuver === 'braking';
    state.input.handbrakeKeyHeld = maneuver === 'drift' && t >= 0.5 && t < 0.8;
    state.input.handbrakeValue = state.input.handbrakeKeyHeld ? 1 : 0;
    state.steering.frontWheelAngle = ['braking', 'acceleration'].includes(maneuver) ? 0
      : t < 0.5 ? 0 : ['transition', 'drift'].includes(maneuver) && t >= 1.75 ? -0.16 : 0.16;
    updateSuspension(dt);
    const f = computeTireForces(dt);
    const drag = computeDragForces();
    const mass = state.params.carMassKg;
    const inertia = mass * (L * L + W * W) / 3;
    const torque = f.torque - state.params.yawDamping * inertia * state.body.angularVelocity;
    verletIntegrateAllPoints(dt, (f.forceX + drag.forceX) / mass,
      (f.forceY + drag.forceY) / mass, torque / inertia);
    solveRigidBodyConstraints();
    computeBodyDerivedState(dt);
    maxRoll = Math.max(maxRoll, Math.abs(state.suspension.roll));
    maxYaw = Math.max(maxYaw, Math.abs(state.body.angularVelocity));
    maxSlip = Math.max(maxSlip, ...Object.values(state.wheelSlipAngle).map(Math.abs));
    minLoad = Math.min(minLoad, ...Object.values(state.wheelLoads));
    if (Math.abs((t + dt) - Math.round(t + dt)) < dt / 2) {
      samples.push({ time: +(t + dt).toFixed(3), yaw: state.body.angularVelocity,
        speed: state.body.speed, roll: state.suspension.roll, loads: { ...state.wheelLoads } });
    }
    if (![state.body.speed, state.suspension.roll, ...Object.values(state.wheelLoads)].every(Number.isFinite)) {
      throw new Error('Non-finite coupled physics state');
    }
  }
  return { maneuver, maxRollDegrees: maxRoll * 180 / Math.PI,
    maxSlipDegrees: maxSlip * 180 / Math.PI, maxYaw, minLoad,
    finalSpeed: state.body.speed, finalHeading: state.body.heading, samples };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const report = {};
  for (const maneuver of ['acceleration', 'braking', 'cornering', 'transition', 'drift']) {
    report[maneuver] = {
      baseline: compareRun({ enabled: false, sensitivity: 0, maneuver }),
      tiresOnly: compareRun({ enabled: false, maneuver }),
      suspension: compareRun({ maneuver }),
      frontBar: compareRun({ frontBar: 40000, rearBar: 0, maneuver }),
      rearBar: compareRun({ frontBar: 0, rearBar: 40000, maneuver }),
    };
  }
  process.stdout.write(JSON.stringify(report, null, 2) + '\n');
}
